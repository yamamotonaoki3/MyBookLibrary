// 依存を持たない定数。サーバー（proxy）とブラウザの両方から使う。

/**
 * ブラウザを開いている間だけ残る目印の Cookie の名前（#782）。
 * 有効期限を付けないので、ブラウザを閉じると消える。ログイン保持なしでログインしたときに、ブラウザが発行する。
 * サーバー（proxy）がこの Cookie を見て、「ログイン保持なしのセッションは、ブラウザを閉じたら未ログイン」を、最初のリクエストから判定する。
 * 安全性の根拠ではない（ブラウザ側で作れる）。根拠は、トークン側の有効期限（保持なしは 8 時間）。
 */
export const BROWSER_SESSION_COOKIE = "mbl_browser_session";

/**
 * ログアウト済みの目印の Cookie の名前（#784）。
 * Auth.js は、セッションを取得するたびにセッション Cookie を再発行する。ログアウトの直前に飛んでいたセッション取得の応答が、
 * サインアウトで消えたあとに届くと、Cookie が書き戻され、ログアウトが取り消される。
 * そこで、ログアウトの最初にこの目印を発行し、proxy が、トークンが有効でも未ログインとして扱う（復活のタイミングによらない）。
 */
export const SIGNED_OUT_COOKIE = "mbl_signed_out";

/**
 * 目印の有効期間（秒）。セッションの最大の有効期間（Auth.js の既定の 30 日）に合わせる。
 * 書き戻された古いセッションが、目印の失効後に有効に戻らないようにするため。目印は、ログイン成功のとき、サーバーが消す。
 */
export const SIGNED_OUT_MARKER_SECONDS = 30 * 24 * 60 * 60;
